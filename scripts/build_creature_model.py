#!/usr/bin/env python3
"""Compile a reviewed GeckoLib .bbmodel into native Horizon renderer tables.

Never hand-edit the generated Rust: the Blockbench .bbmodel is the single
geometry/animation source of truth. Requires only Python's standard library.
"""
from __future__ import annotations
import argparse, base64, json, math, re
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
DEFAULT_MODEL=ROOT/"project/models/creatures/ashen_sentinel.bbmodel"
DEFAULT_RUST=ROOT/"project/src/crpg_generated_models.rs"
DEFAULT_TEXTURE=ROOT/"project/assets/claude_rpg/textures/entity/ashen_sentinel.png"

def fail(message):
    raise ValueError("Invalid creature source: "+message)

def rust_str(value):
    return json.dumps(value,ensure_ascii=True)

def fl(value):
    f=float(value)
    if not math.isfinite(f): fail("nonfinite coordinate")
    result=f"{f:.6f}".rstrip("0").rstrip(".")
    if "." not in result: result+=".0"
    return result+"f32"

def vec3(value):
    if not isinstance(value,list) or len(value)!=3: fail("expected vec3")
    return "["+", ".join(fl(x) for x in value)+"]"

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--model",type=Path,default=DEFAULT_MODEL)
    parser.add_argument("--rust",type=Path,default=DEFAULT_RUST)
    parser.add_argument("--texture",type=Path,default=DEFAULT_TEXTURE)
    args=parser.parse_args()
    source=json.loads(args.model.read_text(encoding="utf-8"))
    if source.get("meta",{}).get("model_format")!="geckolib_model":
        fail("source must be a GeckoLib model")
    elements=source.get("elements",[])
    cubes=[el for el in elements if el.get("type")=="cube"]
    groups=source.get("groups",[])
    textures=source.get("textures",[])
    if not cubes or not groups: fail("missing cubes or bones")
    if len(textures)!=1: fail("expected a single entity texture")
    texture=textures[0]
    uri=texture.get("source","")
    if not uri.startswith("data:image/png;base64,"): fail("embedded PNG is required")
    png=base64.b64decode(uri.split(",",1)[1],validate=True)
    if png[:8]!=bytes([137,80,78,71,13,10,26,10]): fail("invalid PNG signature")
    width=int.from_bytes(png[16:20],"big"); height=int.from_bytes(png[20:24],"big")
    resolution=source.get("resolution",{})
    if width!=resolution.get("width") or height!=resolution.get("height"):
        fail(f"PNG dimensions {width}x{height} must match project UV {resolution}")
    if width>256 or height>256: fail("texture exceeds 256x256")
    ids=[node.get("uuid") for node in groups+elements]
    if len(set(ids))!=len(ids): fail("duplicate UUID")
    by_uuid={node["uuid"]:node for node in groups+elements}
    group_ids={g["uuid"] for g in groups}
    parent={}
    seen=set()
    def walk(nodes,owner=None):
        for entry in nodes:
            uuid=entry if isinstance(entry,str) else entry.get("uuid")
            if uuid not in by_uuid: fail("outliner refers to missing node "+str(uuid))
            if uuid in seen: fail("duplicate outliner reference "+str(uuid))
            seen.add(uuid); parent[uuid]=owner
            if not isinstance(entry,str):
                if uuid not in group_ids: fail("non-group with children")
                walk(entry.get("children",[]),uuid)
    walk(source.get("outliner",[]))
    # Non-cube elements (locators) remain available for effects but do not emit cubes.
    missing=set(ids)-seen
    if missing: fail("unlisted nodes: "+str(missing))
    bone_names={g["name"] for g in groups}
    if len(bone_names)!=len(groups): fail("duplicate bone names")
    if "root" not in bone_names or "head" not in bone_names: fail("missing essential bones")
    for c in cubes:
        if c.get("type")!="cube": fail("native renderer only supports cubes")
        if any(float(lo)>=float(hi) for lo,hi in zip(c["from"],c["to"])):
            fail("cube dimension inverted: "+c["name"])
    out=["// @generated by scripts/build_creature_model.py; do not edit.\n",
         "// Source: project/models/creatures/ashen_sentinel.bbmodel\n",
         "#[derive(Clone,Copy,Debug)]\n",
         "pub struct GeneratedBone { pub name:&'static str, pub parent:Option<&'static str>, pub pivot:[f32;3], pub rotation:[f32;3] }\n",
         "#[derive(Clone,Copy,Debug)]\n",
         "pub struct GeneratedCube { pub name:&'static str, pub bone:&'static str, pub from:[f32;3], pub to:[f32;3], pub origin:[f32;3], pub rotation:[f32;3] }\n",
         "#[derive(Clone,Copy,Debug)]\n",
         "pub struct GeneratedKey { pub clip:&'static str, pub bone:&'static str, pub channel:&'static str, pub time:f32, pub value:[f32;3] }\n",
         "pub const SENTINEL_BONES:&[GeneratedBone]=&[\n"]
    for g in groups:
        p=parent[g["uuid"]]
        pval="Some("+rust_str(by_uuid[p]["name"])+")" if p else "None"
        out.append(f" GeneratedBone{{name:{rust_str(g['name'])},parent:{pval},pivot:{vec3(g['origin'])},rotation:{vec3(g.get('rotation',[0,0,0]))}}},\n")
    out.append("];\npub const SENTINEL_CUBES:&[GeneratedCube]=&[\n")
    for c in cubes:
        p=parent[c["uuid"]]
        if p not in group_ids: fail("cube "+c["name"]+" is not assigned to a bone")
        out.append(f" GeneratedCube{{name:{rust_str(c['name'])},bone:{rust_str(by_uuid[p]['name'])},from:{vec3(c['from'])},to:{vec3(c['to'])},origin:{vec3(c.get('origin',[0,0,0]))},rotation:{vec3(c.get('rotation',[0,0,0]))}}},\n")
    out.append("];\npub const SENTINEL_KEYS:&[GeneratedKey]=&[\n")
    animations=source.get("animations",[])
    names=set()
    for anim in animations:
        clip=anim["name"]
        if clip in names: fail("duplicate animation "+clip)
        names.add(clip)
        length=float(anim["length"])
        for uuid,animator in anim.get("animators",{}).items():
            if uuid not in group_ids: fail("animator targets missing bone")
            bone=by_uuid[uuid]["name"]
            for key in animator.get("keyframes",[]):
                channel=key["channel"]
                if channel not in ("rotation","position","scale"):
                    continue
                t=float(key["time"])
                if not 0<=t<=length: fail("key beyond clip "+clip)
                points=key.get("data_points",[])
                if not points: fail("empty key point")
                point=points[0]
                value=[]
                for axis in "xyz":
                    try:value.append(float(point.get(axis,0)))
                    except ValueError:fail("Molang key not supported by native renderer")
                out.append(f" GeneratedKey{{clip:{rust_str(clip)},bone:{rust_str(bone)},channel:{rust_str(channel)},time:{fl(t)},value:{vec3(value)}}},\n")
    out.append("];\n")
    args.rust.parent.mkdir(parents=True,exist_ok=True)
    args.rust.write_text("".join(out),encoding="utf-8")
    args.texture.parent.mkdir(parents=True,exist_ok=True)
    args.texture.write_bytes(png)
    print(f"Generated {len(groups)} bones, {len(cubes)} cubes, {len(animations)} animations; texture {width}x{height}")

if __name__=="__main__":
    main()
